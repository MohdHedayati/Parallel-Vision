<#
.SYNOPSIS
  LIVE DEMO (about 1 minute). Run this in front of the examiners.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\demo.ps1
  powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 -Image C:\path\photo.jpg   # use your own picture
  powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 -NoOpen                    # do not pop up the graphs

  What it shows, in order:
    1. unit tests + MPI correctness (every backend gives identical output)
    2. console demo: correctness table, dispatcher (heuristic vs calibrated), speedups for all 11 operations
    3. MPI run on 1, 2 and 4 processes
    4. every algorithm applied to a real image through the command-line tool
    5. graphs (PNG) generated by Python/matplotlib from the numbers just measured -> opened on screen

  Everything is written to results\demo\ (CSV files, images\, and the PNG graphs).
#>
param(
    [string]$Image = "",
    [switch]$NoOpen,
    [switch]$Rebuild
)
$ErrorActionPreference = "Continue"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$env:PATH = "C:\msys64\ucrt64\bin;" + $env:PATH
$out = "results\demo"
New-Item -ItemType Directory -Force "$out\images" | Out-Null

$mpiexec = (Get-Command mpiexec -ErrorAction SilentlyContinue).Source
if (-not $mpiexec) { $mpiexec = "C:\Program Files\Microsoft MPI\Bin\mpiexec.exe" }
$py = (Get-Command python -All | Where-Object { $_.Source -notlike "*msys64*" } | Select-Object -First 1).Source

if (-not $Image) {
    foreach ($c in @("demo\input.jpg", "results\sample_input.jpg", "C:\Windows\Web\Wallpaper\Spotlight\img14.jpg")) {
        if (Test-Path $c) { $Image = $c; break }
    }
}
function Step($n, $msg) { Write-Host "`n############ $n  $msg" -ForegroundColor Cyan }
$t0 = Get-Date

if ($Rebuild -or -not (Test-Path "build\bin\pv_demo.exe")) {
    Step 0 "Building (first run only)"
    & "$root\build.ps1" -DPV_WITH_MPI=ON | Select-Object -Last 3
}

Step 1 "Correctness: unit tests, then MPI on 4 processes (output must equal the sequential result)"
& build\bin\pv_tests.exe
& $mpiexec -n 4 build\bin\pv_mpi_tests.exe

Step 2 "Console demo: correctness, dispatcher, speedups"
& build\bin\pv_demo.exe $out

Step 3 "MPI: Canny on a 2048x2048 image with 1, 2 and 4 processes"
$first = $true
foreach ($n in 1,2,4) {
    $lines = & $mpiexec -n $n build\bin\pv_mpi_bench.exe 2 2048
    $lines | Select-Object -Last 1
    if ($first) { $lines | Out-File -Encoding ascii "$out\mpi_demo.csv"; $first = $false }
    else        { $lines | Select-Object -Skip 1 | Out-File -Append -Encoding ascii "$out\mpi_demo.csv" }
}

if ($Image) {
    Step 4 "Every algorithm on a real picture ($Image)"
    Copy-Item $Image "$out\images\input.jpg" -Force
    foreach ($cmd in "gray","blur","median","sobel","prewitt","laplacian","canny","threshold","equalize","erode","dilate") {
        $line = & build\bin\pv.exe $cmd $Image "$out\images\$cmd.png"
        Write-Host ("  {0,-10} {1}" -f $cmd, $line)
    }
} else { Write-Host "(no sample image found - skipping step 4; pass -Image path)" -ForegroundColor Yellow }

Step 5 "Graphs (Python / matplotlib)"
& $py scripts\make_demo_figures.py $out
if (-not $NoOpen) {
    foreach ($f in "fig_demo_montage.png", "fig_demo_speedup.png", "fig_demo_dispatch.png", "fig_demo_mpi.png") {
        if (Test-Path "$out\$f") { Start-Process (Resolve-Path "$out\$f") }
    }
}
$secs = [int]((Get-Date) - $t0).TotalSeconds
Write-Host "`nDone in $secs s.  Files: $root\$out" -ForegroundColor Green
